from fpdf import FPDF
import io
from datetime import datetime


def _safe(text):
    """Strip characters outside latin-1 so fpdf core fonts don't crash."""
    return text.encode('latin-1', 'replace').decode('latin-1')


class PaperIQReport(FPDF):

    def header(self):
        self.set_font('Helvetica', 'B', 15)
        self.set_fill_color(30, 60, 114)
        self.set_text_color(255, 255, 255)
        self.cell(0, 12, '  WriteWell Research AI - Analysis Report', ln=True, fill=True)
        self.set_text_color(0, 0, 0)
        self.ln(4)

    def footer(self):
        self.set_y(-15)
        self.set_font('Helvetica', 'I', 8)
        self.set_text_color(130, 130, 130)
        self.cell(0, 10, f'Page {self.page_no()} | Generated by WriteWell Research AI | {datetime.now().strftime("%Y-%m-%d")}', align='C')

    def section_title(self, title):
        self.set_font('Helvetica', 'B', 12)
        self.set_fill_color(230, 240, 255)
        self.set_text_color(30, 60, 114)
        self.cell(0, 9, f'  {title}', ln=True, fill=True)
        self.set_text_color(0, 0, 0)
        self.ln(2)

    def body_text(self, text, size=10):
        self.set_font('Helvetica', '', size)
        self.multi_cell(0, 6, _safe(str(text)))
        self.ln(2)

    def metric_row(self, label, value, bar=True):
        self.set_font('Helvetica', 'B', 10)
        self.cell(60, 7, _safe(str(label)))
        self.set_font('Helvetica', '', 10)
        val_str = f'{value:.1f}/100' if isinstance(value, float) else _safe(str(value))
        self.cell(20, 7, val_str)
        if bar and isinstance(value, (int, float)):
            # Draw a simple bar
            bar_w = int((value / 100) * 80)
            x, y = self.get_x(), self.get_y()
            self.set_fill_color(200, 220, 255)
            self.rect(x, y + 1, 80, 5, 'F')
            self.set_fill_color(30, 100, 200)
            self.rect(x, y + 1, bar_w, 5, 'F')
            self.ln(8)
        else:
            self.ln()


def generate_report(filename, analysis, sections, summaries):
    """Generate a PDF report and return bytes."""
    pdf = PaperIQReport()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    # ── Overview ────────────────────────────────────────────────────────────
    pdf.section_title('Document Overview')
    pdf.metric_row('Word Count', analysis['word_count'], bar=False)
    pdf.metric_row('Sentence Count', analysis['sentence_count'], bar=False)
    pdf.metric_row('Sections Detected', len(sections), bar=False)
    pdf.metric_row('Overall Sentiment', analysis['sentiment_label'], bar=False)
    pdf.ln(4)

    # ── Writing Quality Scores ───────────────────────────────────────────────
    pdf.section_title('Writing Quality Scores')
    pdf.metric_row('Language Score', analysis['language'])
    pdf.metric_row('Coherence Score', analysis['coherence'])
    pdf.metric_row('Reasoning Score', analysis['reasoning'])
    pdf.metric_row('Lexical Sophistication', analysis['lexical'])
    pdf.metric_row('Readability Score', analysis['readability'])
    pdf.ln(4)

    # ── Section Summaries ────────────────────────────────────────────────────
    pdf.section_title('Section Summaries')
    for section, summary in summaries.items():
        if summary:
            pdf.set_font('Helvetica', 'B', 10)
            pdf.cell(0, 7, _safe(f'> {section}'), ln=True)
            pdf.body_text(summary[:600] + ('...' if len(summary) > 600 else ''))

    # ── Writing Issues ───────────────────────────────────────────────────────
    if analysis['issues']:
        pdf.add_page()
        pdf.section_title('Writing Issues Detected')
        for issue in analysis['issues']:
            pdf.set_font('Helvetica', 'B', 10)
            pdf.cell(0, 7, _safe(f"{issue['type']}  (count: {issue['count']})"), ln=True)
            pdf.body_text(issue['detail'])

    # ── Vocabulary Suggestions ───────────────────────────────────────────────
    if analysis['vocab_suggestions']:
        pdf.section_title('Vocabulary Improvement Suggestions')
        pdf.set_font('Helvetica', '', 10)
        for weak, strong in analysis['vocab_suggestions'][:15]:
            pdf.cell(0, 7, _safe(f'  "{weak}"  ->  "{strong}"'), ln=True)
        pdf.ln(4)

    # ── Top Keywords ────────────────────────────────────────────────────────
    pdf.section_title('Top Keywords')
    pdf.set_font('Helvetica', '', 10)
    kw_line = '  |  '.join([f'{w} ({c})' for w, c in analysis['word_freq'][:12]])
    pdf.multi_cell(0, 7, _safe(kw_line))

    return bytes(pdf.output())
